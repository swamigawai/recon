"""Enterprise Deployability Pack Generator.

Packages standalone Python adapters, schema contracts, CI/CD specifications,
distroless Dockerfiles, and GitHub Actions pipelines into a zero-dependency production bundle.
"""

from __future__ import annotations

import io
import json
from typing import Any, Optional
import zipfile


def generate_dockerfile(adapter_name: str = "adapter", python_version: str = "3.11-slim") -> str:
    """Generates an air-gapped, unprivileged Dockerfile for the synthesized adapter."""
    return f"""# ==============================================================================
# Recon Air-Gapped Integration Runner
# Target Adapter: {adapter_name}.py
# Security Profile: Unprivileged non-root (UID 10001), zero external network egress
# ==============================================================================

FROM python:{python_version} as runner

# Create non-root system user and group
RUN groupadd -g 10001 recon && \\
    useradd -u 10001 -g recon -s /bin/sh -m recon

WORKDIR /app

# Copy integration assets
COPY --chown=recon:recon adapter.py target_contract.json recon_mapping_spec.json ./

USER recon:recon

# Environment hardening
ENV PYTHONUNBUFFERED=1 \\
    PYTHONDONTWRITEBYTECODE=1 \\
    RECON_AIRGAP=1

ENTRYPOINT ["python", "adapter.py"]
"""


def generate_github_workflow(contract_name: str = "integration", quarantine_threshold: float = 0.05) -> str:
    """Generates a production GitHub Actions CI/CD pipeline enforcing contract conformance."""
    pct = round(quarantine_threshold * 100, 1)
    return f"""# ==============================================================================
# GitHub Actions: Recon Integration Conformance Gate
# Target Contract: {contract_name}
# Enforcement: Strict schema validation & quarantine threshold (< {pct}%)
# ==============================================================================

name: Recon Data Conformance Gate

on:
  push:
    branches: [ main, master ]
  pull_request:
    branches: [ main, master ]
  workflow_dispatch:
    inputs:
      data_path:
        description: 'Path to incoming dataset to validate'
        required: true
        default: 'incoming_data.csv'

jobs:
  recon-conformance-check:
    name: Verify Contract Conformance
    runs-on: ubuntu-latest

    steps:
      - name: Checkout Code
        uses: actions/checkout@v4

      - name: Set up Python 3.11
        uses: actions/setup-python@v5
        with:
          python-version: "3.11"
          cache: "pip"

      - name: Install Recon Engine
        run: |
          python -m pip install --upgrade pip
          pip install recon-engine || pip install -e .

      - name: Execute Recon Conformance Gate
        run: |
          python -m recon.cli gate \\
            --source "${{{{ github.event.inputs.data_path || 'incoming_data.csv' }}}}" \\
            --contract target_contract.json \\
            --quarantine-threshold {quarantine_threshold} \\
            --output-json
"""


def generate_bundle_readme(
    contract_name: str,
    version: str,
    pass_rate: float,
    total_records: int = 0,
) -> str:
    """Generates a comprehensive enterprise README explaining the bundle contents and operations."""
    return f"""# {contract_name} — Enterprise Integration Deliverables
Generated by **Recon — The Integration Readiness Engine**  
Contract Version: `{version}` · Validation Yield: **{pass_rate}%** · Total Records: **{total_records}**

---

## 📦 Bundle Deliverables

| File | Purpose |
| :--- | :--- |
| `adapter.py` | Standalone, reviewable Python transformation adapter generated via AST. |
| `target_contract.json` | Exact schema contract definition with cryptographic SHA-256 fingerprint. |
| `recon_mapping_spec.json` | Versioned mapping specification decisions for automated CI/CD runs. |
| `readiness_report.md` | Formal preflight certification report, risk log, and mathematical parity proof. |
| `Dockerfile` | Air-gapped, unprivileged micro-container definition for Kubernetes / Docker deployment. |
| `.github/workflows/recon-gate.yml` | Ready-to-run GitHub Actions pipeline for automated pull-request validation. |

---

## 🚀 Execution Guide

### 1. Standalone Python Execution (Zero Cloud Dependencies)
```bash
# Execute directly in any Python 3.10+ environment
python -c "
import adapter, json
sample = {{'raw_key': 'value'}}
output, errors = adapter.transform_record(sample)
print('Transformed:', output if not errors else 'Quarantined:', errors)
"
```

### 2. Air-Gapped Docker Execution
```bash
# Build lightweight local container
docker build -t recon-{contract_name}:latest .

# Run in an isolated container
docker run --rm --read-only recon-{contract_name}:latest
```

### 3. Automated CI/CD Conformance Gate
Copy `.github/workflows/recon-gate.yml` into your target repository to automatically block invalid payloads on Git pull requests:
```bash
mkdir -p .github/workflows
cp .github/workflows/recon-gate.yml .github/workflows/
```
"""


def create_deployment_bundle_zip(
    session_id: str,
    adapter_code: str,
    contract_json: str | dict[str, Any],
    mapping_spec_json: str | dict[str, Any],
    report_md: str,
    contract_name: str = "integration",
    version: str = "1.0.0",
    pass_rate: float = 100.0,
    total_records: int = 0,
) -> bytes:
    """Assembles all integration deliverables into an in-memory ZIP archive."""
    
    # Normalize JSON strings
    if isinstance(contract_json, dict):
        contract_str = json.dumps(contract_json, indent=2, ensure_ascii=False)
    else:
        contract_str = str(contract_json)

    if isinstance(mapping_spec_json, dict):
        spec_str = json.dumps(mapping_spec_json, indent=2, ensure_ascii=False)
    else:
        spec_str = str(mapping_spec_json) if mapping_spec_json else "{}"

    dockerfile_content = generate_dockerfile(adapter_name=f"{contract_name}_adapter")
    workflow_content = generate_github_workflow(contract_name=contract_name)
    readme_content = generate_bundle_readme(
        contract_name=contract_name,
        version=version,
        pass_rate=pass_rate,
        total_records=total_records,
    )

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("adapter.py", adapter_code)
        zf.writestr("target_contract.json", contract_str)
        zf.writestr("recon_mapping_spec.json", spec_str)
        zf.writestr("readiness_report.md", report_md)
        zf.writestr("Dockerfile", dockerfile_content)
        zf.writestr(".github/workflows/recon-gate.yml", workflow_content)
        zf.writestr("README.md", readme_content)

    return buffer.getvalue()
